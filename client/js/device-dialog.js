import { channelLabel, formatValue } from './axis-mapping.js';
import {
  CONDITIONS,
  DEFAULT_PULSE_MS,
  DEVICE_TYPES,
  PULSE_MAX_MS,
  PULSE_MIN_MS,
  allCombinations,
  buttonState,
  formatPositions,
  isPressed,
  matchRule,
  newDeviceId,
  parsePositions,
  positionIndex,
  positionsFromRange,
  unknownReason,
} from './devices.js';
import { featureHint, featureOptionsHtml, featureTitle } from './features.js';
import { ModalForm, fieldValue, readNumber } from './joystick-dialogs.js';

const escapeHtml = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

/** An empty field is null ("nothing"); anything else is a number, NaN (and flagged) when it isn't one. */
function readOptionalNumber(input) {
  if (input.value.trim() === '') {
    input.removeAttribute('aria-invalid');
    return null;
  }
  return readNumber(input);
}

const optionalValue = (n) => (n === null ? '' : fieldValue(n));

/** Value of a button <select> option: "<channel>:<port>" (ports can contain ":"). */
const sourceKey = (input) => (input ? `${input.channel}:${input.joystick}` : '');

function parseSourceKey(key) {
  if (!key) return null;
  const colon = key.indexOf(':');
  return { channel: Number(key.slice(0, colon)), joystick: key.slice(colon + 1) };
}

const sameInput = (a, b) => a && b && a.joystick === b.joystick && a.channel === b.channel;

/** Most rules generated by "All combinations" (4 buttons). */
const MAX_COMBINATION_BUTTONS = 4;

/**
 * Creating and editing a virtual device: its name, type, feature, buttons and what the type needs
 * (rules, positions, pulse values). Buttons can be picked from a list or by pressing them
 * (Detect). Edits are previewed against the live buttons and only saved with Save.
 */
export class DeviceDialog extends ModalForm {
  #onSave;
  /** { locomotive, device (saved, or null for a new one), features, bindings, devices (all on the locomotive) } */
  #ctx = null;
  /** The device being edited; numbers are NaN while a field is invalid, null for "nothing". */
  #draft = null;
  /** Fields the user set; the others follow the chosen feature (new devices only). */
  #touched = new Set();
  #joysticks = [];
  /** port -> latest JoystickInput */
  #inputs = new Map();
  /** Input row waiting for a button press, or -1. */
  #detecting = -1;
  /** Server state of the saved device (a step switch's position). */
  #state = null;
  #lastSourceOptions = '';

  /** @param {{ onSave: (change: object) => Promise<{ ok: boolean, error?: string }> }} callbacks */
  constructor(dialog, { onSave }) {
    super(dialog);
    this.#onSave = onSave;

    this.$('name').addEventListener('input', () => {
      this.#draft.name = this.$('name').value;
      this.#touched.add('name');
    });
    this.$('type').addEventListener('change', () => this.#setType(this.$('type').value));
    this.$('feature').addEventListener('change', () => {
      this.#draft.feature = this.$('feature').value;
      this.#followFeature();
      this.#renderFeature();
      this.#renderTypeFields();
    });

    this.$('add-input').addEventListener('click', () => {
      this.#draft.inputs.push(null);
      this.#syncRules();
      this.#renderInputs();
      this.#renderRules();
      this.#detect(this.#draft.inputs.length - 1);
    });
    this.$('inputs').addEventListener('change', (event) => {
      const select = event.target.closest('select[data-field="source"]');
      if (!select) return;
      this.#setInput(Number(select.closest('tr').dataset.index), parseSourceKey(select.value));
    });
    this.$('inputs').addEventListener('click', (event) => {
      const button = event.target.closest('button[data-action]');
      if (!button) return;
      const index = Number(button.closest('tr').dataset.index);
      if (button.dataset.action === 'detect') this.#detect(this.#detecting === index ? -1 : index);
      if (button.dataset.action === 'delete') this.#removeInput(index);
    });

    this.$('rules').addEventListener('change', (event) => {
      const select = event.target.closest('select[data-condition]');
      if (!select) return;
      const rule = this.#draft.rules[Number(select.closest('tr').dataset.index)];
      rule.when[Number(select.dataset.condition)] = select.value;
      this.#renderLive();
    });
    this.$('rules').addEventListener('input', (event) => {
      const input = event.target.closest('input[data-field="value"]');
      if (!input) return;
      this.#draft.rules[Number(input.closest('tr').dataset.index)].value = readOptionalNumber(input);
      this.#renderLive();
    });
    this.$('rules').addEventListener('click', (event) => {
      const button = event.target.closest('button[data-action="delete"]');
      if (!button) return;
      this.#draft.rules.splice(Number(button.closest('tr').dataset.index), 1);
      this.#renderRules();
      this.$('add-rule').focus();
    });
    this.$('add-rule').addEventListener('click', () => {
      this.#draft.rules.push({ when: this.#draft.inputs.map(() => 'any'), value: null });
      this.#renderRules();
      this.$('rules').querySelector('tr:last-child select')?.focus();
    });
    this.$('all-combinations').addEventListener('click', () => this.#fillCombinations());

    this.$('positions').addEventListener('input', () => {
      this.#draft.positionsText = this.$('positions').value;
      this.#touched.add('positions');
      this.#renderPositions();
    });
    this.$('positions-from-description').addEventListener('click', () => {
      const positions = positionsFromRange(this.#feature()?.range);
      if (!positions) return;
      this.#draft.positionsText = formatPositions(positions);
      this.$('positions').value = this.#draft.positionsText;
      this.#renderPositions();
    });
    for (const field of ['wrap', 'repeat']) {
      this.$(field).addEventListener('change', () => {
        this.#draft[field] = this.$(field).checked;
        this.#renderLive();
      });
    }
    const pulseFields = { 'on-press': 'onPress', 'on-release': 'onRelease', rest: 'rest', duration: 'durationMs' };
    for (const [role, field] of Object.entries(pulseFields)) {
      this.$(role).addEventListener('input', () => {
        const input = this.$(role);
        this.#draft[field] = field === 'onPress' || field === 'onRelease' ? readOptionalNumber(input) : readNumber(input);
        this.#touched.add('pulse');
        this.#renderLive();
      });
    }

    this.$('remove').addEventListener('click', () => this.#remove());
    dialog.addEventListener('close', () => (this.#detecting = -1));
  }

  /**
   * @param {{ locomotive: string, device: object | null, features: object[], bindings: object[],
   *           devices: object[], joysticks: object[], inputs: Map<string, object>, state: object | null }} ctx
   */
  open({ locomotive, device, features, bindings, devices, joysticks, inputs, state }) {
    this.#ctx = { locomotive, device, features, bindings, devices };
    this.#joysticks = joysticks;
    this.#inputs = new Map(inputs);
    this.#state = state;
    this.#detecting = -1;
    this.#lastSourceOptions = '';
    this.#touched = new Set(device ? ['name', 'positions', 'pulse'] : []);
    this.#draft = {
      id: device?.id ?? newDeviceId(),
      name: device?.name ?? '',
      type: device?.type ?? 'combo',
      feature: device?.feature ?? '',
      inputs: device ? device.inputs.map((i) => ({ ...i })) : [null, null],
      rules: device?.type === 'combo' ? device.rules.map((r) => ({ when: [...r.when], value: r.value })) : [],
      positionsText: device?.type === 'stepper' ? formatPositions(device.positions) : '',
      wrap: device?.type === 'stepper' ? device.wrap : false,
      repeat: device?.type === 'stepper' ? device.repeat : false,
      onPress: device?.type === 'pulse' ? device.onPress : 1,
      onRelease: device?.type === 'pulse' ? device.onRelease : null,
      rest: device?.type === 'pulse' ? device.rest : 0,
      durationMs: device?.type === 'pulse' ? device.durationMs : DEFAULT_PULSE_MS,
    };
    if (!device) this.#syncRules();
    this.#normalizeInputs();

    this.$('title').textContent = device ? device.name : 'New virtual device';
    this.$('subtitle').textContent = locomotive;
    this.$('name').value = this.#draft.name;
    this.$('type').value = this.#draft.type;
    this.$('feature').innerHTML = featureOptionsHtml(features);
    this.$('feature').value = this.#draft.feature;
    this.$('positions').value = this.#draft.positionsText;
    this.$('wrap').checked = this.#draft.wrap;
    this.$('repeat').checked = this.#draft.repeat;
    this.#renderPulseFields();
    for (const el of this.dialog.querySelectorAll('[aria-invalid]')) el.removeAttribute('aria-invalid');
    this.$('remove').hidden = !device;

    this.#renderFeature();
    this.#renderTypeFields();
    this.show();
    (device ? this.$('name') : this.$('type')).focus();
  }

  setJoysticks(joysticks) {
    if (!this.isOpen) return;
    this.#joysticks = joysticks;
    // Rebuilding the rows closes an open dropdown: only when the buttons to choose from changed.
    if (this.#sourceOptionsHtml() !== this.#lastSourceOptions) this.#renderInputs();
    else this.#renderLive();
  }

  /** Latest values of a joystick: live preview, and Detect. */
  setInput(input) {
    if (!this.isOpen) return;
    const previous = this.#inputs.get(input.port)?.values;
    this.#inputs.set(input.port, input);
    if (this.#detecting >= 0 && previous && input.values) {
      const joystick = this.#joysticks.find((j) => j.port === input.port);
      const channel = input.values.findIndex(
        (raw, i) => joystick?.channels[i] === 'button' && isPressed(raw) && previous[i] === 0,
      );
      if (channel >= 0) {
        const row = this.#detecting;
        this.#detecting = -1;
        this.#setInput(row, { joystick: input.port, channel });
        this.$('inputs').querySelector(`tr[data-index="${row}"] select`)?.focus();
        return;
      }
    }
    this.#renderLive();
  }

  setDeviceState(state) {
    if (!this.isOpen || state.id !== this.#ctx.device?.id) return;
    this.#state = state;
    this.#renderLive();
  }

  submit() {
    const { device, error } = this.#collect();
    if (error) return this.setError(error);
    void this.send(() => this.#onSave({ kind: 'device', device }));
  }

  // ---------- editing ----------

  #type() {
    return DEVICE_TYPES[this.#draft.type];
  }

  #feature() {
    return this.#ctx.features.find((f) => f.topic === this.#draft.feature) ?? null;
  }

  #setType(type) {
    this.#draft.type = type;
    this.#detecting = -1;
    this.#normalizeInputs();
    this.#syncRules();
    this.#followFeature();
    this.#renderTypeFields();
  }

  /** As many input rows as the type has: step switches always show Up and Down. */
  #normalizeInputs() {
    const { inputs } = this.#draft;
    const { min, max } = this.#type();
    const rows = this.#draft.type === 'stepper' ? max : Math.min(Math.max(inputs.length, min), max);
    this.#draft.inputs = Array.from({ length: rows }, (_, i) => inputs[i] ?? null);
  }

  #setInput(index, input) {
    this.#draft.inputs[index] = input;
    this.#renderInputs();
    this.#renderRules(); // column titles name the buttons
  }

  #removeInput(index) {
    this.#draft.inputs.splice(index, 1);
    for (const rule of this.#draft.rules) rule.when.splice(index, 1);
    if (this.#detecting === index) this.#detecting = -1;
    this.#syncRules();
    this.#renderInputs();
    this.#renderRules();
    this.$('add-input').focus();
  }

  /** Wait for the next button pressed on any joystick being read; -1 stops waiting. */
  #detect(index) {
    this.#detecting = index;
    this.#renderInputs();
  }

  /**
   * Rules need a condition per button. Until a value is filled in, they are all the
   * combinations of the buttons; after that, a new button is "any" in every rule.
   */
  #syncRules() {
    const count = this.#draft.inputs.length;
    const { rules } = this.#draft;
    const untouched = rules.every((r) => r.value === null);
    if (untouched && count <= MAX_COMBINATION_BUTTONS) {
      this.#draft.rules = allCombinations(count).map((when) => ({ when, value: null }));
      return;
    }
    for (const rule of rules) {
      rule.when = Array.from({ length: count }, (_, i) => rule.when[i] ?? 'any');
    }
  }

  /** One rule per combination of the buttons, keeping the values of rules that name exactly one. */
  #fillCombinations() {
    const count = this.#draft.inputs.length;
    if (count > MAX_COMBINATION_BUTTONS) {
      this.setError(`All combinations is for up to ${MAX_COMBINATION_BUTTONS} buttons (16 rules).`);
      return;
    }
    const previous = this.#draft.rules;
    this.#draft.rules = allCombinations(count).map((when) => {
      const same = previous.find((r) => r.when.every((c, i) => c === when[i]));
      return { when, value: same ? same.value : null };
    });
    this.setError('');
    this.#renderRules();
  }

  /** A new device takes its name, positions and pulse values from the feature until the user sets them. */
  #followFeature() {
    const feature = this.#feature();
    if (!feature) return;
    if (!this.#touched.has('name')) {
      this.#draft.name = feature.title;
      this.$('name').value = feature.title;
    }
    const positions = positionsFromRange(feature.range);
    if (!this.#touched.has('positions') && positions) {
      this.#draft.positionsText = formatPositions(positions);
      this.$('positions').value = this.#draft.positionsText;
    }
    // Impulse buttons are documented as "-1 = released / 1 = pressed": rest low, pulse high.
    const { ticks, documented } = feature.range;
    if (!this.#touched.has('pulse') && documented && ticks.length === 2) {
      Object.assign(this.#draft, { onPress: ticks[1], onRelease: null, rest: ticks[0] });
      this.#renderPulseFields();
    }
  }

  async #remove() {
    const { device, locomotive } = this.#ctx;
    if (!window.confirm(`Remove the virtual device "${device.name}" from ${locomotive}?`)) return;
    await this.send(() => this.#onSave({ kind: 'remove-device', id: device.id }));
  }

  /** The device to save, or the first problem with the form. */
  #collect() {
    const d = this.#draft;
    const { locomotive } = this.#ctx;
    const { roles } = this.#type();
    if (!d.feature) return { error: 'Choose the feature this device drives.' };

    if (d.type === 'stepper' && !d.inputs[0]) return { error: 'Choose the Up button.' };
    const missing = d.inputs.findIndex((i) => !i);
    if (d.type !== 'stepper' && missing >= 0) return { error: `Choose a button for ${roles[missing]}, or remove it.` };
    if (d.inputs.length === 0) return { error: 'Add a button.' };
    for (const [i, input] of d.inputs.entries()) {
      const twin = d.inputs.findIndex((other, j) => j > i && sameInput(input, other));
      if (twin >= 0) return { error: `${roles[i]} and ${roles[twin]} are the same button.` };
    }
    const inputs = d.inputs.filter(Boolean);
    const base = { id: d.id, locomotive, name: d.name.trim() || featureTitle(d.feature), type: d.type, feature: d.feature, inputs };

    if (d.type === 'combo') {
      if (d.rules.length === 0) return { error: 'Add a rule: which buttons send which value.' };
      const bad = d.rules.findIndex((r) => r.value !== null && !Number.isFinite(r.value));
      if (bad >= 0) return { error: `Rule ${bad + 1}: the value is not a number (leave it empty to send nothing).` };
      if (d.rules.every((r) => r.value === null)) return { error: 'Give at least one rule a value to send.' };
      return { device: { ...base, rules: d.rules.map((r) => ({ when: [...r.when], value: r.value })) } };
    }
    if (d.type === 'stepper') {
      const { positions, error } = parsePositions(d.positionsText);
      if (error) return { error: `Positions: ${error}` };
      return { device: { ...base, positions, wrap: d.wrap, repeat: d.repeat } };
    }
    for (const [field, label] of [['onPress', 'On press'], ['onRelease', 'On release']]) {
      if (d[field] !== null && !Number.isFinite(d[field])) return { error: `${label}: enter a number, or leave it empty.` };
    }
    if (d.onPress === null && d.onRelease === null) return { error: 'Enter a value to send on press, on release, or both.' };
    if (!Number.isFinite(d.rest)) return { error: 'Enter the rest value.' };
    if (!Number.isInteger(d.durationMs) || d.durationMs < PULSE_MIN_MS || d.durationMs > PULSE_MAX_MS) {
      return { error: `The pulse lasts from ${PULSE_MIN_MS} to ${PULSE_MAX_MS} ms (whole milliseconds).` };
    }
    return { device: { ...base, onPress: d.onPress, onRelease: d.onRelease, rest: d.rest, durationMs: d.durationMs } };
  }

  // ---------- rendering ----------

  #renderFeature() {
    const feature = this.#feature();
    this.$('feature-hint').textContent = feature ? featureHint(feature) : 'The SimRail input this device drives.';
    this.$('description-box').hidden = !feature?.description;
    this.$('description').textContent = feature?.description ?? '';
    this.$('positions-from-description').disabled = !positionsFromRange(feature?.range);
  }

  #renderTypeFields() {
    const { type } = this.#draft;
    this.$('type-hint').textContent = this.#type().summary;
    for (const section of ['combo', 'stepper', 'pulse']) this.$(section).hidden = section !== type;
    this.$('add-input').hidden = type !== 'combo' || this.#draft.inputs.length >= this.#type().max;
    this.#renderInputs();
    this.#renderRules();
    this.#renderPositions();
  }

  #renderPulseFields() {
    const d = this.#draft;
    this.$('on-press').value = optionalValue(d.onPress);
    this.$('on-release').value = optionalValue(d.onRelease);
    this.$('rest').value = fieldValue(d.rest);
    this.$('duration').value = fieldValue(d.durationMs);
  }

  /** <option>s for picking a button: the button channels of every joystick, by joystick. */
  #sourceOptionsHtml() {
    const listed = new Set();
    const option = (input, label) => {
      listed.add(sourceKey(input));
      return `<option value="${escapeHtml(sourceKey(input))}">${escapeHtml(label)}</option>`;
    };
    const groups = this.#joysticks
      .map((j) => {
        const buttons = j.channels.map((kind, i) => (kind === 'button' ? i : -1)).filter((i) => i >= 0);
        if (buttons.length === 0) return '';
        const name = j.state === 'open' ? j.name : `${j.name} (not read)`;
        // The joystick's name too: a closed <select> shows only the option.
        const options = buttons.map((channel) => option({ joystick: j.port, channel }, `${j.name} · ${channelLabel(j, channel)}`));
        return `<optgroup label="${escapeHtml(name)}">${options.join('')}</optgroup>`;
      })
      .join('');
    // Saved buttons of joysticks that aren't listed (unplugged) or aren't buttons any more (mask changed).
    const extra = this.#draft.inputs
      .filter((i) => i && !listed.has(sourceKey(i)))
      .map((i) => option(i, this.#sourceLabel(i)))
      .join('');
    return groups + extra;
  }

  #sourceLabel(input) {
    const joystick = this.#joysticks.find((j) => j.port === input.joystick);
    if (!joystick) return `${input.joystick} · channel ${input.channel + 1} (not connected)`;
    const label = channelLabel(joystick, input.channel);
    return joystick.channels[input.channel] === 'button' ? `${joystick.name} · ${label}` : `${joystick.name} · ${label} (not a button)`;
  }

  #renderInputs() {
    const { type, inputs } = this.#draft;
    const { roles, min } = this.#type();
    const options = this.#sourceOptionsHtml();
    this.#lastSourceOptions = options;
    const removable = type === 'combo' && inputs.length > min;
    // The rows are rebuilt: keep the keyboard focus where it was.
    const active = this.$('inputs').contains(document.activeElement) ? document.activeElement : null;
    const refocus = active && {
      row: active.closest('tr').dataset.index,
      selector: active.matches('select') ? 'select' : `[data-action="${active.dataset.action}"]`,
    };

    this.$('inputs').innerHTML = inputs
      .map((input, i) => {
        const optional = type === 'stepper' && i > 0;
        const none = optional ? '<option value="">None</option>' : '<option value="">Choose a button…</option>';
        const detecting = this.#detecting === i;
        return (
          `<tr data-index="${i}"><td class="device-role">${roles[i]}</td>` +
          `<td><select data-field="source" aria-label="${roles[i]} button">${none}${options}</select></td>` +
          `<td><button type="button" class="btn btn-small btn-ghost" data-action="detect" aria-pressed="${detecting}"` +
          ` title="Press a button on a joystick to pick it">${detecting ? 'Press a button…' : 'Detect'}</button></td>` +
          `<td><span class="pill" data-role="input-state">—</span></td>` +
          `<td>${removable ? `<button type="button" class="icon-btn" data-action="delete" aria-label="Remove ${roles[i]}" title="Remove ${roles[i]}">✕</button>` : ''}</td></tr>`
        );
      })
      .join('');
    this.$('inputs').querySelectorAll('select').forEach((select, i) => (select.value = sourceKey(inputs[i])));
    this.$('add-input').hidden = type !== 'combo' || inputs.length >= this.#type().max;
    if (refocus) this.$('inputs').querySelector(`tr[data-index="${refocus.row}"] ${refocus.selector}`)?.focus();

    const notes = [];
    if (!this.#joysticks.some((j) => j.state === 'open' && j.channels.includes('button'))) {
      notes.push('No joystick with buttons is being read: turn on Read for one in the Joysticks tab.');
    } else if (this.#detecting >= 0) {
      notes.push(`Press the button for ${roles[this.#detecting]} on any joystick being read.`);
    }
    for (const input of inputs) {
      if (!input) continue;
      const binding = this.#ctx.bindings.find((b) => sameInput(b, input));
      if (binding) notes.push(`${this.#sourceLabel(input)} also drives ${featureTitle(binding.feature)} directly; both are sent.`);
      const others = this.#ctx.devices.filter((d) => d.id !== this.#draft.id && d.inputs.some((i) => sameInput(i, input)));
      if (others.length) notes.push(`${this.#sourceLabel(input)} is also in ${others.map((d) => `“${d.name}”`).join(', ')}.`);
    }
    this.$('inputs-hint').textContent = notes.join(' ');
    this.$('inputs-hint').hidden = notes.length === 0;
    this.#renderLive();
  }

  #renderRules() {
    const { inputs, rules, type } = this.#draft;
    if (type !== 'combo') return;
    const { roles } = this.#type();
    const heads = inputs.map((input, i) => `<th title="${escapeHtml(input ? this.#sourceLabel(input) : 'No button chosen')}">${roles[i]}</th>`);
    this.$('rules-head').innerHTML = `<tr><th>#</th>${heads.join('')}<th>Send</th><th><span class="sr-only">Remove</span></th></tr>`;
    const conditionOptions = Object.entries(CONDITIONS)
      .map(([value, label]) => `<option value="${value}">${label}</option>`)
      .join('');
    this.$('rules').innerHTML = rules
      .map((rule, r) => {
        const cells = rule.when.map(
          (_, i) =>
            `<td><select data-condition="${i}" aria-label="Rule ${r + 1}: ${roles[i]}">${conditionOptions}</select></td>`,
        );
        return (
          `<tr data-index="${r}"><td class="num">${r + 1}</td>${cells.join('')}` +
          `<td><input type="number" step="any" data-field="value" value="${optionalValue(rule.value)}" placeholder="nothing"` +
          ` aria-label="Rule ${r + 1}: value to send" /></td>` +
          `<td><button type="button" class="icon-btn" data-action="delete" aria-label="Remove rule ${r + 1}" title="Remove rule ${r + 1}">✕</button></td></tr>`
        );
      })
      .join('');
    this.$('rules').querySelectorAll('tr').forEach((row, r) => {
      row.querySelectorAll('select').forEach((select, i) => (select.value = rules[r].when[i]));
    });
    this.$('rules-table').hidden = rules.length === 0;
    this.$('rules-empty').hidden = rules.length > 0;
    this.$('all-combinations').disabled = inputs.length > MAX_COMBINATION_BUTTONS;
    this.#renderLive();
  }

  #renderPositions() {
    if (this.#draft.type !== 'stepper') return;
    const { positions, error } = parsePositions(this.#draft.positionsText);
    const preview = this.$('positions-preview');
    const input = this.$('positions');
    input.toggleAttribute('aria-invalid', Boolean(error) && this.#draft.positionsText.trim() !== '');
    preview.innerHTML = error
      ? `<span class="muted">${escapeHtml(this.#draft.positionsText.trim() ? error : 'e.g. 0, 1, 2 or 0..7 (whole numbers from 0 to 7)')}</span>`
      : positions.map((p) => `<span class="position" data-value="${p}">${escapeHtml(formatValue(p))}</span>`).join('');
    this.#renderLive();
  }

  /** Everything that follows the buttons and the game: input states, the matching rule, the position. */
  #renderLive() {
    const d = this.#draft;
    const { roles } = this.#type();
    const states = d.inputs.map((input) => this.#stateOf(input));
    this.$('inputs').querySelectorAll('[data-role="input-state"]').forEach((pill, i) => {
      const input = d.inputs[i];
      const state = states[i];
      pill.textContent = state === null ? '—' : state ? 'Pressed' : 'Released';
      pill.dataset.on = String(state === true);
      pill.title = input && state === null ? unknownReason(this.#joysticks.find((j) => j.port === input.joystick), input.channel) : '';
    });

    const readout = this.$('readout');
    readout.dataset.kind = 'note';
    // A step switch's Down is optional; every other button is needed.
    const missing = d.inputs.findIndex((input, i) => !input && !(d.type === 'stepper' && i > 0));
    const pressedText = () =>
      d.inputs.map((input, i) => (input ? `${roles[i]} ${states[i] ? 'pressed' : 'released'}` : null)).filter(Boolean).join(' · ');
    let index = -1;

    if (missing >= 0) {
      readout.textContent = `Choose the button for ${roles[missing]}: pick it from the list, or press Detect and then the button.`;
    } else if (d.inputs.some((input, i) => input && states[i] === null)) {
      readout.textContent = 'Not all chosen buttons are being read, so there is no live preview.';
    } else if (d.type === 'combo') {
      index = matchRule(d.rules, states);
      const rule = d.rules[index];
      readout.dataset.kind = rule && rule.value !== null ? 'value' : 'note';
      if (!rule) readout.textContent = `${pressedText()}: no rule matches, nothing is sent`;
      else if (rule.value === null) readout.textContent = `${pressedText()} → rule ${index + 1}: sends nothing`;
      else readout.textContent = `${pressedText()} → rule ${index + 1} → ${formatValue(rule.value)}`;
    } else {
      readout.dataset.kind = 'value';
      readout.textContent = pressedText();
    }
    for (const row of this.$('rules').rows) row.classList.toggle('is-active', Number(row.dataset.index) === index);

    // A step switch's position in game: known for the saved device's feature.
    const game = d.type === 'stepper' && this.#ctx.device?.feature === d.feature ? (this.#state?.value ?? null) : null;
    const { positions } = parsePositions(d.positionsText);
    const at = game === null || !positions ? -1 : positionIndex(positions, game);
    for (const chip of this.$('positions-preview').querySelectorAll('.position')) {
      chip.classList.toggle('is-active', game !== null && Number(chip.dataset.value) === positions?.[at]);
    }
    const gameEl = this.$('position-game');
    if (d.type !== 'stepper') gameEl.textContent = '';
    else if (game === null) {
      gameEl.textContent = this.#ctx.device?.feature === d.feature
        ? 'In game: not known yet (SimRail not connected, or this train has no such input).'
        : 'The position in game shows here once the device is saved.';
    } else {
      const where = at >= 0 ? `position ${at + 1} of ${positions.length}` : 'between positions';
      gameEl.textContent = `In game: ${formatValue(game)}${positions ? ` · ${where}` : ''}`;
    }
  }

  #stateOf(input) {
    if (!input) return null;
    const joystick = this.#joysticks.find((j) => j.port === input.joystick);
    return buttonState(joystick, this.#inputs.get(input.joystick), input.channel);
  }
}
